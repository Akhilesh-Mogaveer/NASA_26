"""NASA Data Ingestion, Quality, and Preview API Routes.

Provides endpoints to trigger ingestion, query status, inspect data quality reports,
and preview normalized observations.
"""
from typing import Optional, Dict, Any
from fastapi import APIRouter, Query, HTTPException

from app.config import settings
from app.models.schemas import (
    DataIngestResponse,
    DataStatusResponse,
    DataPreviewResponse,
)
from app.services.pipeline import (
    run_ingestion_pipeline,
    get_latest_quality_report,
    get_normalized_preview,
    pipeline_state,
)

router = APIRouter(prefix="/data", tags=["Data Ingestion & Validation"])


@router.post("/ingest", response_model=DataIngestResponse, summary="Trigger Ingestion and Validation")
async def trigger_ingestion(
    max_rows_per_file: Optional[int] = Query(None, description="Max rows per file (None for full dataset)"),
) -> DataIngestResponse:
    """Run data ingestion, coordinate/timestamp validation, and normalization for raw MODIS & VIIRS files."""
    report = run_ingestion_pipeline(max_rows_per_file=max_rows_per_file)

    return DataIngestResponse(
        status=pipeline_state.status,
        message=pipeline_state.message,
        total_records=report.get("total_records", 0),
        valid_records=report.get("valid_records", 0),
        invalid_records=report.get("invalid_records", 0),
        number_of_source_files=report.get("number_of_source_files", 0),
        report=report,
    )


@router.get("/status", response_model=DataStatusResponse, summary="Get Ingestion Pipeline Status")
async def get_data_status() -> DataStatusResponse:
    """Get current status of data ingestion pipeline and available raw files."""
    modis_files = list(settings.DATA_RAW_MODIS.glob("*.csv")) if settings.DATA_RAW_MODIS.exists() else []
    viirs_files = list(settings.DATA_RAW_VIIRS.glob("*.csv")) if settings.DATA_RAW_VIIRS.exists() else []
    
    unified_csv = settings.DATA_PROCESSED_DIR / "unified_observations.csv"
    has_processed_data = unified_csv.exists() and unified_csv.stat().st_size > 0

    return DataStatusResponse(
        status=pipeline_state.status,
        message=pipeline_state.message,
        last_run_at=pipeline_state.last_run_at,
        has_processed_data=has_processed_data,
        modis_raw_files=len(modis_files),
        viirs_raw_files=len(viirs_files),
        last_summary=pipeline_state.last_summary,
    )


@router.get("/quality", summary="Get Latest Data Quality Report")
async def get_quality_report() -> Dict[str, Any]:
    """Retrieve the latest data quality report generated by the validation engine."""
    report = get_latest_quality_report()
    if report is None:
        raise HTTPException(
            status_code=404,
            detail="No data quality report found. Please run POST /api/data/ingest first.",
        )
    return report


@router.get("/preview", response_model=DataPreviewResponse, summary="Preview Normalized Fire Observations")
async def preview_normalized_data(
    sensor: Optional[str] = Query(None, description="Filter by sensor: 'MODIS' or 'VIIRS'"),
    status: Optional[str] = Query("valid", description="Filter by processing status: 'valid', 'invalid', or null for all"),
    limit: int = Query(20, ge=1, le=500, description="Max observations to return"),
    offset: int = Query(0, ge=0, description="Pagination offset"),
) -> DataPreviewResponse:
    """Preview a slice of harmonized/normalized active fire observations."""
    preview_data = get_normalized_preview(
        sensor=sensor,
        status=status,
        limit=limit,
        offset=offset,
    )
    return DataPreviewResponse(**preview_data)
